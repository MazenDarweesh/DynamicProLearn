using LearnDynamicPro.Domain.Common;
using LearnDynamicPro.Domain.Entities.AI;

namespace LearnDynamicPro.Domain.Entities;

/// <summary>
/// Represents an AI-generated summary for a specific lesson.
/// Persisted as a SQL Server row; the nested Topics list is stored
/// as a JSON column via EF Core 10's .ToJson() owned-entity mapping.
/// 
/// One-to-one with Lesson (one active summary per lesson at any time).
/// Historical regenerations are handled by replacing the existing row.
/// </summary>
public class LessonSummary : BaseEntity
{
    /// <summary>Foreign key to the parent Lesson.</summary>
    public Guid LessonId { get; set; }

    /// <summary>UTC timestamp when this summary was generated by the Python AI engine.</summary>
    public DateTime GeneratedAt { get; set; } = DateTime.UtcNow;

    /// <summary>
    /// A high-level overview paragraph of the lesson, generated by the AI engine.
    /// Stored as a plain TEXT column (not JSON) because it is a single scalar value.
    /// </summary>
    public string Overview { get; set; } = string.Empty;

    /// <summary>
    /// The structured topic breakdown, serialized as a JSON column.
    /// Each element contains the topic name, explanation, and key points.
    /// </summary>
    public List<SummaryTopic> Topics { get; set; } = new();

    // Navigation
    public Lesson? Lesson { get; set; }
}
