using LearnDynamicPro.Domain.Common;
using LearnDynamicPro.Domain.Entities.AI;

namespace LearnDynamicPro.Domain.Entities;

/// <summary>
/// Represents an AI-generated quiz for a specific lesson.
/// Persisted as a SQL Server row; the nested Questions list is stored
/// as a JSON column via EF Core 10's .ToJson() owned-entity mapping.
/// 
/// One-to-one with Lesson (one active quiz per lesson at any time).
/// Historical regenerations are handled by replacing the existing row.
/// </summary>
public class LessonQuiz : BaseEntity
{
    /// <summary>Foreign key to the parent Lesson.</summary>
    public Guid LessonId { get; set; }

    /// <summary>UTC timestamp when this quiz was generated by the Python AI engine.</summary>
    public DateTime GeneratedAt { get; set; } = DateTime.UtcNow;

    /// <summary>
    /// The structured quiz questions, serialized as a JSON column.
    /// Each element contains the question text, all answer options,
    /// the correct answer ID, and an explanation.
    /// </summary>
    public List<QuizQuestion> Questions { get; set; } = new();

    // Navigation
    public Lesson? Lesson { get; set; }
}
